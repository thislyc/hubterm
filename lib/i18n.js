  let current = 'zh-CN';

  function fmt(str, args) {
    return str.replace(/\{(\d)\}/g, (m, i) => (args[+i] != null ? String(args[+i]) : m));
  }
  function t(key) {
    const args = Array.prototype.slice.call(arguments, 1);
    let s = (STRINGS[current] && STRINGS[current][key]);
    if (s == null) s = STRINGS['zh-CN'][key]; // 缺译回退中文
    if (s == null) return key;                // 再缺回退 key（可读、不崩）
    return args.length ? fmt(s, args) : s;
  }
  function setLang(lang) {
    if (!STRINGS[lang]) return false;
    current = lang;
    try {
      if (typeof localStorage !== 'undefined' && localStorage) localStorage.setItem('hubterm.lang', lang);
    } catch (e) { /* 主进程/测试无 localStorage */ }
    return true;
  }
  function getLang() { return current; }
  function init(localeHint) {
    let saved = null;
    try {
      if (typeof localStorage !== 'undefined' && localStorage) saved = localStorage.getItem('hubterm.lang');
    } catch (e) { /* ignore */ }
    setLang(saved || (/^zh/i.test(String(localeHint || '')) ? 'zh-CN' : 'en'));
    return current;
  }
  function applyDOM(root) {
    const doc = root || document;
    doc.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.getAttribute('data-i18n')); });
    doc.querySelectorAll('[data-i18n-title]').forEach((el) => { el.setAttribute('title', t(el.getAttribute('data-i18n-title'))); });
    doc.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder'))); });
    doc.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.getAttribute('data-i18n-html')); });
  }
  return { t, setLang, getLang, init, applyDOM, STRINGS };
